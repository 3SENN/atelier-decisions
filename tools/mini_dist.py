"""atelier-mini as Atelier's optional download: the folder to host and the manifest Atelier ships.

Atelier downloads the mini only when someone asks for it (Settings › Quick decisions), file by file, and checks
every file against the size and SHA-256 in a manifest compiled into Atelier (src/main/decisions/device/
miniManifest.ts), so whoever hosts the files can't change what runs. This assembles, from the mini's runtime folder
(student/export_mini.py) and llama.cpp's CPU builds:

    <out>/model/      mini.gguf, readout.f32, decision.json, tokenizer.json, tokenizer_config.json
    <out>/server/<platform>/   llama-server and the libraries it loads, llama.cpp's licence
    <out>/miniManifest.ts      for Atelier (paste or copy over src/main/decisions/device/miniManifest.ts)

Hosted as <base>model/... and <base>server/<platform>/... (the layout the manifest's paths assume).

    python tools/mini_dist.py --runtime runs/mini-v05/runtime --version v0.5 --out runs/mini-dist \
        --server win32-x64=models/llama.cpp-b12620/bin --licence models/llama.cpp-b12620/src/LICENSE \
        [--server darwin-arm64=<unpacked llama.cpp macOS build>] [--base https://.../]

A server folder is checked by running its llama-server --version when it is this machine's platform.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

MODEL_FILES = ["mini.gguf", "readout.f32", "decision.json", "tokenizer.json", "tokenizer_config.json"]
HEADER = """/* Copyright (c) 2026 The Atelier Authors. All rights reserved.
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this file,
 * You can obtain one at https://mozilla.org/MPL/2.0/. */

// atelier-mini's optional download (deviceMini.ts): every file with its size and SHA-256. Generated by the
// atelier-decisions project's tools/mini_dist.py from the files it hosts; don't edit by hand.

import type { MiniManifest } from '../deviceMini'

"""


def server_file(name: str) -> bool:
    """llama-server and what it loads, not llama.cpp's other tools."""
    n = name.lower()
    if n in ("llama-server", "llama-server.exe") or n.startswith(("llama-server-impl", "libllama-server-impl")):
        return True
    if n.startswith("ggml-rpc") or n.endswith(".exe") or n.startswith("llama-") and "common" not in n:
        return False
    if n.startswith(("ggml", "libggml", "llama.", "libllama.", "llama-common", "libllama-common", "libomp", "mtmd", "libmtmd")):
        return True
    return n.startswith("license")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def entry(root: Path, path: Path) -> dict:
    return {"path": path.relative_to(root).as_posix(), "size": path.stat().st_size, "sha256": sha256(path)}


def this_platform() -> str:
    arch = {"amd64": "x64", "x86_64": "x64", "arm64": "arm64", "aarch64": "arm64"}.get(os.uname().machine.lower() if hasattr(os, "uname") else os.environ.get("PROCESSOR_ARCHITECTURE", "").lower(), "")
    return {"win32": "win32", "darwin": "darwin", "linux": "linux"}.get(sys.platform, sys.platform) + "-" + arch


def ts_literal(value: object, indent: int = 0) -> str:
    """A JSON value as TypeScript in Atelier's style (prettier --no-semi --single-quote --trailing-comma all)."""
    pad, inner = "  " * indent, "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        keys = (k if k.isidentifier() else "'" + k + "'" for k in value)
        return "{\n" + "".join(f"{inner}{k}: {ts_literal(v, indent + 1)},\n" for k, v in zip(keys, value.values())) + pad + "}"
    if isinstance(value, list):
        if not value:
            return "[]"
        return "[\n" + "".join(f"{inner}{ts_literal(v, indent + 1)},\n" for v in value) + pad + "]"
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return json.dumps(value)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime", type=Path, required=True, help="the mini's runtime folder (student/export_mini.py)")
    parser.add_argument("--version", required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--server", action="append", default=[], help="platform=folder of a llama.cpp CPU build (e.g. win32-x64=models/llama.cpp-b12620/bin)")
    parser.add_argument("--licence", type=Path, help="llama.cpp's LICENSE, shipped next to its server")
    parser.add_argument("--base", default="", help="where the files will be hosted, ending in / (empty: Atelier offers no download yet)")
    args = parser.parse_args()

    model_dir = args.out / "model"
    model_dir.mkdir(parents=True, exist_ok=True)
    model = []
    # vocab.json only with a trimmed vocabulary (student/vocab_trim.py); the runners map ids through it when it is there.
    for name in MODEL_FILES + (["vocab.json"] if (args.runtime / "vocab.json").exists() else []):
        src, dst = args.runtime / name, model_dir / name
        if not src.exists():
            sys.exit(f"{src} is missing")
        if not dst.exists() or dst.stat().st_size != src.stat().st_size or sha256(dst) != sha256(src):
            shutil.copyfile(src, dst)
        model.append(entry(model_dir, dst))

    servers = {}
    for spec in args.server:
        platform, folder = spec.split("=", 1)
        dst_dir = args.out / "server" / platform
        if dst_dir.exists():
            shutil.rmtree(dst_dir)
        dst_dir.mkdir(parents=True)
        for f in sorted(Path(folder).iterdir()):
            if f.is_file() and server_file(f.name):
                shutil.copy2(f, dst_dir / f.name)
        if args.licence:
            shutil.copyfile(args.licence, dst_dir / "LICENSE-llama.cpp")
        exe = dst_dir / ("llama-server.exe" if platform.startswith("win32") else "llama-server")
        if not exe.exists():
            sys.exit(f"{folder} has no llama-server")
        if platform == this_platform():
            out = subprocess.run([str(exe), "--version"], capture_output=True, text=True, timeout=60)
            if out.returncode != 0:
                sys.exit(f"{exe} --version failed with only the selected files:\n{out.stderr[-2000:]}")
            print(f"{platform}: {(out.stdout + out.stderr).strip().splitlines()[-1]}")
        servers[platform] = [entry(dst_dir, f) for f in sorted(dst_dir.iterdir())]

    # Hosted as base + url (model/<file>, server/<platform>/<file>); Atelier installs them as <file> and server/<file>.
    manifest = {"version": args.version, "base": args.base,
                "model": [{"path": m["path"], "url": f"model/{m['path']}", "size": m["size"], "sha256": m["sha256"]} for m in model],
                "servers": {p: [{"path": f["path"], "url": f"server/{p}/{f['path']}", "size": f["size"], "sha256": f["sha256"]} for f in fs]
                            for p, fs in servers.items()}}
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8", newline="\n")
    (args.out / "miniManifest.ts").write_text(HEADER + "export const MINI_MANIFEST: MiniManifest = " + ts_literal(manifest) + "\n",
                                              encoding="utf-8", newline="\n")
    size = sum(m["size"] for m in model)
    print(f"model {size / 1e6:.0f} MB; servers " + ", ".join(f"{p} {sum(f['size'] for f in fs) / 1e6:.0f} MB ({len(fs)} files)" for p, fs in servers.items()))
    print(f"wrote {args.out / 'miniManifest.ts'}")


if __name__ == "__main__":
    main()
